-- ── Vagas ────────────────────────────────────────────────────────────────────
create table if not exists vagas_extraidas (
    id                 bigint generated by default as identity primary key,
    gmail_message_id   text,
    cargo              text,
    fonte              text,
    tecnologias        jsonb default '[]'::jsonb,
    links_candidatura  jsonb default '[]'::jsonb,
    status_aplicacao   text default 'nova',
    created_at         timestamptz not null default now()
);

-- v3: uma linha POR VAGA (antes era uma por e-mail — num digest da Catho
-- com 10 vagas, só a última sobrevivia ao upsert por gmail_message_id).
alter table vagas_extraidas add column if not exists vaga_uid        text;
alter table vagas_extraidas add column if not exists empresa         text;
alter table vagas_extraidas add column if not exists local           text;
alter table vagas_extraidas add column if not exists modelo_trabalho text;
alter table vagas_extraidas add column if not exists salario         text;
alter table vagas_extraidas add column if not exists score_match     integer default 0;
alter table vagas_extraidas add column if not exists requisitos      jsonb default '[]'::jsonb;
alter table vagas_extraidas add column if not exists tipo_email      text;
alter table vagas_extraidas add column if not exists data_email      text;
alter table vagas_extraidas add column if not exists task_id         text;

-- Um e-mail pode ter N vagas: remove a unicidade antiga por e-mail…
alter table vagas_extraidas drop constraint if exists vagas_extraidas_gmail_message_id_key;
-- …e garante unicidade por vaga.
create unique index if not exists vagas_extraidas_vaga_uid_key on vagas_extraidas (vaga_uid);
create index if not exists vagas_extraidas_created_at_idx on vagas_extraidas (created_at desc);

-- ── Certificados ─────────────────────────────────────────────────────────────
create table if not exists certificados_portfolio (
    id               bigint generated by default as identity primary key,
    gmail_message_id text unique,
    plataforma       text,
    nome_curso       text,
    caminho_local    text,          -- URL do arquivo no Google Drive
    status_extracao  text,          -- extraido | pendente
    created_at       timestamptz not null default now()
);

-- ── Alertas de acesso ────────────────────────────────────────────────────────
create table if not exists log_acessos_otp (
    id               bigint generated by default as identity primary key,
    plataforma       text,
    tipo_alerta      text,          -- otp | recuperacao_senha | alerta_novo_login
    codigo_extraido  text,          -- links de recuperação NÃO são gravados (só o domínio)
    created_at       timestamptz not null default now()
);

-- ── Despesas ─────────────────────────────────────────────────────────────────
create table if not exists despesas_domesticas (
    id               bigint generated by default as identity primary key,
    gmail_message_id text unique,
    estabelecimento  text,
    categoria        text,          -- boleto_fatura | pix | recibo | assinatura | cobranca
    valor            numeric(12, 2),
    data_despesa     date,
    origem_recurso   text default 'email',
    created_at       timestamptz not null default now()
);

-- Tabelas criadas antes deste schema podem ter data_despesa obrigatória; o
-- pipeline grava despesas com valor mesmo quando o e-mail não traz a data.
alter table despesas_domesticas alter column data_despesa drop not null;
